async function seed() {
    const connection = await mysql.createConnection({
        host: process.env.DB_HOST || 'localhost',
        port: process.env.DB_PORT || 3306,
        user: process.env.DB_USER || 'root',
        password: process.env.DB_PASSWORD || '',
        database: process.env.DB_NAME || 'autobees'
    });

    console.log('Connected to MySQL...');
    let totalWords = 0;

    for (const [letterKey, categories] of Object.entries(dictionaryData)) {
        // Normalize "ا" to "أ" if necessary. 
        // Wait, the key in JSON is "ا", but in validLetters it is "أ". 
        // And standard arabic for first letter is usually Aleph with Hamza or other forms.
        // The previous analysis says user provided "ا" but meant "أ".
        const letter = (letterKey === 'ا') ? 'أ' : letterKey;

        for (const [category, words] of Object.entries(categories)) {
            if (Array.isArray(words)) {
                for (const word of words) {
                    const normWord = normalizeArabic(word.trim());
                    const normLetter = normalizeArabic(letter);
                    await connection.execute(
                        'INSERT IGNORE INTO dictionary (word, category, letter) VALUES (?, ?, ?)',
                        [normWord, category, normLetter]
                    );
                    totalWords++;
                }
            }
        }
    }

    console.log(`Seeding completed. Inserted/Ignored ${totalWords} words.`);
    await connection.end();
}

seed().catch(err => {
    console.error('Seeding failed:', err);
    process.exit(1);
});
